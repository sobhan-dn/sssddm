function buildClinicSummary() {
  const servicesText = clinicProfile.services
    .map((service) => `- ${service.title}: ${service.summary}`)
    .join("\n");

  return [
    `${clinicProfile.name} در ${clinicProfile.city}`,
    clinicProfile.tagline,
    `مدیریت: ${clinicProfile.manager}`,
    `تلفن پذیرش: ${clinicProfile.phone}`,
    "خدمات اصلی:",
    servicesText,
    `نکته بیمه: ${clinicProfile.insuranceNote}`,
    `سیاست نوبت‌دهی: ${clinicProfile.bookingPolicy}`,
    `هشدار مهم: ${clinicProfile.emergencyNotice}`,
  ].join("\n");
}

